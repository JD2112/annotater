class TestFormatAndSamples:
    def test_format_and_sample_columns_preserved_in_order(self):
        df = _result_df(coord_format=["GT:AD"], coord_S1=["0/1:8,2"],
                        coord_S2=["./.:."])
        vcf = convert_df_to_vcf(df)
        chrom = next(l for l in vcf.splitlines() if l.startswith("#CHROM"))
        assert chrom.endswith("\tFORMAT\tS1\tS2")
        record = vcf.splitlines()[-1].split("\t")
        assert record[8:] == ["GT:AD", "0/1:8,2", "./.:."]

    def test_sample_name_collision_prefix_is_reversed(self):
        # A sample named "start" is stored as sample_start by the
        # parser (collision rename) -> coord_sample_start in the
        # result; the export header must show the original name.
        df = _result_df(coord_format=["GT"], coord_sample_start=["0/0"])
        vcf = convert_df_to_vcf(df)
        chrom = next(l for l in vcf.splitlines() if l.startswith("#CHROM"))
        assert chrom.endswith("\tFORMAT\tstart")

    def test_no_format_column_keeps_eight_columns(self):
        vcf = convert_df_to_vcf(_result_df())
        chrom = next(l for l in vcf.splitlines() if l.startswith("#CHROM"))
        assert chrom == "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO"


class TestEscaping:
    def test_problematic_characters_are_escaped_consistently(self):
        df = _result_df(
            annot_feature=["a b"],
            annot_source=["x;y"],
            annot_ID=["k=v"],
            annot_gene_name=["a,b"],
        )
        vcf = convert_df_to_vcf(df)
        record = vcf.splitlines()[-1].split("\t")
        info = record[7]
        # Repository-established encoding: space -> '_', ';' -> '|',
        # '=' -> ':'; commas are valid in String values and pass through.
        assert info == (
            "ANNOT_feature=a_b;ANNOT_source=x|y;ANNOT_ID=k:v;"
            "ANNOT_gene_name=a,b"
        )
        # The INFO field must stay a single tab-separated column.
        assert len(record) == 8


class TestCollisions:
    def test_original_info_already_containing_annot_key_wins(self):
        # The source INFO already declares ANNOT_feature: the exporter
        # must not overwrite or duplicate it.
        df = _result_df(coord_info=["DP=10;ANNOT_feature=orig"])
        vcf = convert_df_to_vcf(df)
        record = vcf.splitlines()[-1].split("\t")
        assert record[7] == "DP=10;ANNOT_feature=orig"

    def test_duplicate_keys_after_sanitization_first_wins(self):
        # '01' sanitizes to x_01, and a column literally named 'x_01'
        # also maps to ANNOT_x_01: deterministic first-in-frame-order
        # wins, no duplicate keys in the INFO field.
        df = pd.DataFrame({
            "coord_chr": ["chr1"], "coord_start": [100],
            "coord_end": [101], "has_overlap": [True],
            "annot_01": ["first"], "annot_x_01": ["second"],
        })
        vcf = convert_df_to_vcf(df)
        record = vcf.splitlines()[-1].split("\t")
        info = record[7]
        assert info.count("ANNOT_x_01=") == 1
        assert info == "ANNOT_x_01=first"


class TestUnmatchedAndMultiplicity:
    def test_unmatched_row_no_bogus_values(self):
        df = _result_df(
            coord_info=["DP=10"], annot_feature=[pd.NA],
            annot_strand=[pd.NA], has_overlap=[False],
        )
        vcf = convert_df_to_vcf(df)
        record = vcf.splitlines()[-1].split("\t")
        assert record[7] == "DP=10"
        for token in ("nan", "None", "<NA>"):
            assert token not in vcf

    def test_one_variant_two_matches_exports_two_records(self):
        df = pd.DataFrame({
            "coord_chr": ["chr1", "chr1"],
            "coord_start": [99, 99],
            "coord_end": [100, 100],
            "coord_id": ["snv1", "snv1"],
            "coord_ref": ["A", "A"],
            "coord_alt": ["T", "T"],
            "coord_qual": [50.0, 50.0],
            "coord_filter": ["PASS", "PASS"],
            "coord_info": ["DP=10", "DP=10"],
            "annot_feature": ["geneA", "geneB"],
            "has_overlap": [True, True],
        })
        vcf = convert_df_to_vcf(df)
        records = _data_records(vcf)
        assert records == [
            ["chr1", "100", "snv1", "A", "T", "50", "PASS",
             "DP=10;ANNOT_feature=geneA"],
            ["chr1", "100", "snv1", "A", "T", "50", "PASS",
             "DP=10;ANNOT_feature=geneB"],
        ]

    def test_engine_parity_of_exported_records(self, tmp_path):
        a = _export_text(tmp_path, "bedtools")
        b = _export_text(tmp_path, "polars-bio")
        assert _data_records(a) == _data_records(b)


