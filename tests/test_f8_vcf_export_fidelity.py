"""
Task C / F8 — annotated VCF export fidelity.

The exported annotated VCF must:
- preserve the original record-level content the parse/result path
  actually retained (ID, REF, ALT, QUAL, FILTER, the raw INFO field
  including END, FORMAT and sample columns);
- append annotation-derived INFO keys under the ANNOT_* namespace
  (never bare annotation column names) and declare every emitted key
  with a valid ##INFO line;
- keep POS semantics correct (POS = coord_start + 1), keep row
  multiplicity (one record per query-annotation pair), and export
  unmatched retained rows as valid records without bogus values.

Expected VCF content in these tests is hand-computed from the fixtures
below — never generated by running the exporter under test.
"""

import re

import pandas as pd
import pytest

from streamlit_app.config import Settings
from streamlit_app.core.engine_registry import build_engine
from streamlit_app.core.normalization import normalize_intervals
from streamlit_app.core.parsers import GFFParser, VCFParser
from streamlit_app.core.schema import canonicalize_annotation_result
from streamlit_app.streamlit_app import convert_df_to_vcf


# ---------------------------------------------------------------------------
# Fixtures (tiny, human-readable, hand-auditable)
# ---------------------------------------------------------------------------

QUERY_VCF = (
    b"##fileformat=VCFv4.2\n"
    b"##INFO=<ID=DP,Number=.,Type=Integer,Description=\"read depth\">\n"
    b"##INFO=<ID=END,Number=1,Type=Integer,Description=\"end position\">\n"
    b"##INFO=<ID=SVTYPE,Number=1,Type=String,Description=\"structural variant type\">\n"
    b"##FORMAT=<ID=GT,Number=1,Type=String,Description=\"genotype\">\n"
    b"##FORMAT=<ID=DP,Number=1,Type=Integer,Description=\"depth\">\n"
    b"#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
    # A/B: SNV with ID, QUAL, FILTER, INFO (DP=10), FORMAT/samples.
    b"chr1\t100\tsnv1\tA\tT\t50\tPASS\tDP=10\tGT:DP\t0/1:8\n"
    # D: symbolic variant carrying END; QUAL/FILTER missing.
    b"chr1\t300\t.\tC\t<DEL>\t.\t.\tEND=400;SVTYPE=DEL\tGT:DP\t./.:.\n"
    # F: variant with no annotation match (left join retains it).
    b"chr1\t500\tnomatch\tG\tA\t.\t.\t.\tGT:DP\t1/1:3\n"
)

ANNOT_GFF = (
    b"##gff-version 3\n"
    # E: geneA and geneB both overlap the SNV at POS 100.
    b"chr1\tens\tgene\t1\t120\t.\t+\t.\tID=geneA;Name=geneA\n"
    b"chr1\tens\tgene\t90\t110\t.\t-\t.\tID=geneB;Name=geneB\n"
    # geneC overlaps nothing in the query.
    b"chr1\tens\tgene\t900\t950\t.\t+\t.\tID=geneC;Name=geneC\n"
)

# The GFF parser publishes, in this order, the metadata columns:
# strand, source, feature, score, frame, attributes, ID, Name, gene_id,
# gene_name, transcript_id, gene_type, gene_biotype, Parent. With the
# fixture above, score/frame are "." (skipped in INFO) and the
# gene_* / Parent attributes are missing (skipped). So a matched SNV
# row gains exactly: ANNOT_strand, ANNOT_source, ANNOT_feature,
# ANNOT_attributes, ANNOT_ID, ANNOT_Name — in that order.
_GENE_A_ANNOT_INFO = (
    "ANNOT_strand=+;ANNOT_source=ens;ANNOT_feature=gene;"
    "ANNOT_attributes=ID:geneA|Name:geneA;ANNOT_ID=geneA;ANNOT_Name=geneA"
)
_GENE_B_ANNOT_INFO = (
    "ANNOT_strand=-;ANNOT_source=ens;ANNOT_feature=gene;"
    "ANNOT_attributes=ID:geneB|Name:geneB;ANNOT_ID=geneB;ANNOT_Name=geneB"
)

EXPECTED_RECORDS = [
    # E: one source variant, two annotation hits -> two records,
    # original fields identical in both, annotation payload differs.
    ["chr1", "100", "snv1", "A", "T", "50", "PASS",
     f"DP=10;{_GENE_A_ANNOT_INFO}", "GT:DP", "0/1:8"],
    ["chr1", "100", "snv1", "A", "T", "50", "PASS",
     f"DP=10;{_GENE_B_ANNOT_INFO}", "GT:DP", "0/1:8"],
    # D: unmatched; original INFO (END=400) must survive verbatim.
    ["chr1", "300", ".", "C", "<DEL>", ".", ".",
     "END=400;SVTYPE=DEL", "GT:DP", "./.:."],
    # F: unmatched; empty original INFO -> bare "." (no bogus values).
    ["chr1", "500", "nomatch", "G", "A", ".", ".",
     ".", "GT:DP", "1/1:3"],
]

EXPECTED_HEADER_NAMES = [
    "ANNOT_strand", "ANNOT_source", "ANNOT_feature", "ANNOT_score",
    "ANNOT_frame", "ANNOT_attributes", "ANNOT_ID", "ANNOT_Name",
    "ANNOT_gene_id", "ANNOT_gene_name", "ANNOT_transcript_id",
    "ANNOT_gene_type", "ANNOT_gene_biotype", "ANNOT_Parent",
]


def _export_text(tmp_path, engine: str = "bedtools") -> str:
    """Full real path: parse -> normalize -> engine -> canonicalize -> export."""
    vcf_path = tmp_path / "query.vcf"
    gff_path = tmp_path / "annot.gff"
    vcf_path.write_bytes(QUERY_VCF)
    gff_path.write_bytes(ANNOT_GFF)

    coord_df = normalize_intervals(
        VCFParser.parse(str(vcf_path)), coordinate_system="1-based"
    )
    annot_df = normalize_intervals(
        GFFParser.parse(str(gff_path)), coordinate_system="1-based"
    )
    engine_obj = build_engine(engine, mode="overlap")
    raw = engine_obj.intersect(coord_df, annot_df, how="left")
    result = canonicalize_annotation_result(raw, coord_df, annot_df)
    return convert_df_to_vcf(result)


def _data_records(vcf_text: str):
    return [
        line.split("\t")
        for line in vcf_text.splitlines()
        if line and not line.startswith("#")
    ]


def _header_lines(vcf_text: str):
    return [line for line in vcf_text.splitlines() if line.startswith("##")]


