class TestVCFExportRealPath:
    def test_full_export_matches_hand_computed_records(self, tmp_path):
        vcf = _export_text(tmp_path)
        assert _data_records(vcf) == EXPECTED_RECORDS

    def test_header_line_includes_format_and_samples(self, tmp_path):
        vcf = _export_text(tmp_path)
        chrom_line = next(
            l for l in vcf.splitlines() if l.startswith("#CHROM")
        )
        assert chrom_line == (
            "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1"
        )

    def test_every_emitted_annot_key_is_declared(self, tmp_path):
        vcf = _export_text(tmp_path)
        declared = set(re.findall(
            r"##INFO=<ID=([A-Za-z0-9_]+),", vcf
        ))
        emitted = set()
        for record in _data_records(vcf):
            info = record[7]
            if info != ".":
                for token in info.split(";"):
                    key = token.split("=")[0]
                    if key.startswith("ANNOT_"):
                        emitted.add(key)
        assert emitted
        assert emitted <= declared, (
            f"emitted but undeclared: {sorted(emitted - declared)}"
        )

    def test_all_annot_columns_are_declared_in_header(self, tmp_path):
        vcf = _export_text(tmp_path)
        for name in EXPECTED_HEADER_NAMES:
            assert re.search(
                rf"##INFO=<ID={re.escape(name)},Number=\.,"
                rf"Type=String,Description=", vcf
            ), f"missing ##INFO declaration for {name}"

    def test_original_info_keys_are_not_fabricated_in_header(self, tmp_path):
        # The parser does not retain the original ##INFO/##FORMAT
        # definition lines, so the exporter must not invent them.
        vcf = _export_text(tmp_path)
        assert "##INFO=<ID=DP," not in vcf
        assert "##INFO=<ID=END," not in vcf
        assert "##FORMAT=" not in vcf

    def test_source_line_identifies_annotater_with_version(self, tmp_path):
        vcf = _export_text(tmp_path)
        assert f"##source=AnnotateR {Settings.VERSION}" in vcf.splitlines()
        assert "##source=AnnotatorApp" not in vcf

    def test_original_header_metadata_is_not_invented(self, tmp_path):
        # Only generated lines: fileformat/source/date/INFO declarations.
        for line in _header_lines(_export_text(tmp_path)):
            assert line.startswith(
                ("##fileformat=", "##source=AnnotateR ", "##date=",
                 '##INFO=<ID=ANNOT_')
            ), f"unexpected header line: {line}"

    def test_round_trip_reparse_accepts_export_and_keeps_content(self, tmp_path):
        vcf = _export_text(tmp_path)
        out = tmp_path / "exported.vcf"
        out.write_text(vcf)
        reparsed = VCFParser.parse(str(out))
        norm = normalize_intervals(reparsed, coordinate_system="1-based")

        assert len(norm) == 4  # multiplicity preserved across round trip
        snv = norm.loc[norm["id"] == "snv1"]
        assert len(snv) == 2  # both annotation hits survive the round trip
        for _, row in snv.iterrows():
            assert row["qual"] == 50.0
            assert row["filter"] == "PASS"
            assert row["info"].startswith("DP=10;ANNOT_strand=")
            assert "ANNOT_feature=gene" in row["info"]
        # END=400 in the preserved INFO drives the same span as before.
        dele = norm.loc[norm["alt"] == "<DEL>"].iloc[0]
        assert (dele["start"], dele["end"]) == (299, 400)
        assert "END=400;SVTYPE=DEL" == dele["info"]


