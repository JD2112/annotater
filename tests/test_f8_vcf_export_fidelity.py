def _result_df(**overrides):
    base = {
        "coord_chr": ["chr1"],
        "coord_start": [100],
        "coord_end": [101],
        "coord_id": [pd.NA],
        "coord_ref": ["A"],
        "coord_alt": ["G"],
        "coord_qual": [pd.NA],
        "coord_filter": [pd.NA],
        "annot_feature": ["geneA"],
        "has_overlap": [True],
    }
    base.update(overrides)
    return pd.DataFrame(base)


class TestOriginalInfoPreservation:
    def test_info_appended_not_replaced(self):
        vcf = convert_df_to_vcf(
            _result_df(coord_info=["DP=10"])
        )
        record = vcf.splitlines()[-1].split("\t")
        assert record[7] == "DP=10;ANNOT_feature=geneA"

    def test_end_survives_inside_original_info(self):
        vcf = convert_df_to_vcf(
            _result_df(coord_info=["END=400;SVTYPE=DEL"],
                       coord_alt=["<DEL>"], coord_end=[400])
        )
        record = vcf.splitlines()[-1].split("\t")
        # POS stays the original 1-based POS; END stays in INFO verbatim.
        assert record[1] == "101"
        assert record[4] == "<DEL>"
        assert record[7] == f"END=400;SVTYPE=DEL;ANNOT_feature=geneA"

    def test_flag_only_info_survives(self):
        vcf = convert_df_to_vcf(_result_df(coord_info=["DB"]))
        record = vcf.splitlines()[-1].split("\t")
        assert record[7] == "DB;ANNOT_feature=geneA"

    def test_missing_info_with_annotations(self):
        vcf = convert_df_to_vcf(_result_df())  # no coord_info column
        record = vcf.splitlines()[-1].split("\t")
        assert record[7] == "ANNOT_feature=geneA"

    def test_original_info_only_no_annotations(self):
        vcf = convert_df_to_vcf(
            _result_df(coord_info=["DP=10;END=400"],
                       annot_feature=[pd.NA])
        )
        record = vcf.splitlines()[-1].split("\t")
        assert record[7] == "DP=10;END=400"


class TestAnnotationNamespace:
    def test_keys_namespaced_and_declared(self):
        vcf = convert_df_to_vcf(_result_df())
        header = _header_lines(vcf)
        record = vcf.splitlines()[-1].split("\t")
        assert record[7] == "ANNOT_feature=geneA"
        assert any(
            l == (
                "##INFO=<ID=ANNOT_feature,Number=.,Type=String,"
                'Description="AnnotateR annotation (source column: '
                'annot_feature)">'
            )
            for l in header
        )
        # No bare annotation column name may be emitted as an INFO key.
        assert not re.search(r"(^|;)feature=", record[7])

    def test_multiple_columns_all_declared_in_order(self):
        df = _result_df(annot_feature=["geneA"], annot_ID=["g1"],
                        annot_strand=["+"])
        vcf = convert_df_to_vcf(df)
        record = vcf.splitlines()[-1].split("\t")
        assert record[7] == (
            "ANNOT_feature=geneA;ANNOT_ID=g1;ANNOT_strand=+"
        )
        for key in ("ANNOT_feature", "ANNOT_ID", "ANNOT_strand"):
            assert f"##INFO=<ID={key}," in vcf


