class TestAnnotIdCollisions:
    def test_string_typed_original_annot_declaration_is_kept(self):
        pre = (
            b"##fileformat=VCFv4.2\n"
            b'##INFO=<ID=ANNOT_feature,Number=1,Type=String,'
            b'Description="pre-existing feature">\n'
            b"#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\n"
            b"chr1\t100\tsnv1\tA\tT\t50\tPASS\t.\n"
        )
        out = _full_export(pre)
        header = _header_lines(out)
        original = (
            '##INFO=<ID=ANNOT_feature,Number=1,Type=String,'
            'Description="pre-existing feature">'
        )
        # The original definition stands; no generated duplicate.
        assert header.count(original) == 1
        assert _declaration("ANNOT_feature", "annot_feature") not in header
        # The value is still exported under the original definition.
        assert any(
            "ANNOT_feature=gene" in r.split("\t")[7]
            for r in _record_lines(out)
        )

    def test_incompatible_original_annot_declaration_fails_clearly(self):
        pre = (
            b"##fileformat=VCFv4.2\n"
            b'##INFO=<ID=ANNOT_source,Number=1,Type=Float,'
            b'Description="pre-existing numeric field">\n'
            b"#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\n"
            b"chr1\t100\tsnv1\tA\tT\t50\tPASS\t.\n"
        )
        with pytest.raises(ValueError, match="ANNOT_source"):
            _full_export(pre)


