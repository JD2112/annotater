class TestHeaderRetentionPlumbing:
    def test_parser_attaches_header_lines_in_source_order(self):
        d = Path(tempfile.mkdtemp())
        df = VCFParser.parse(_write(d, "q.vcf", QUERY_VCF))
        assert df.attrs["vcf_header_lines"] == ORIGINAL_HEADER_LINES
        # Retention must not add columns: the schema is unchanged.
        assert "vcf_header_lines" not in df.columns

    def test_vcf_without_header_lines_gets_empty_list(self):
        d = Path(tempfile.mkdtemp())
        minimal = (
            b"#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\n"
            b"chr1\t5\t.\tA\tT\t.\t.\t.\n"
        )
        df = VCFParser.parse(_write(d, "q.vcf", minimal))
        assert df.attrs["vcf_header_lines"] == []

    def test_parse_and_normalize_propagates_header_lines(self):
        d = Path(tempfile.mkdtemp())
        q = parse_and_normalize(_write(d, "q.vcf", QUERY_VCF))
        assert q.attrs["vcf_header_lines"] == ORIGINAL_HEADER_LINES


