class TestStructuralValidity:
    def test_every_used_info_id_has_a_declaration(self):
        out = _full_export(QUERY_VCF)
        header_text = "\n".join(_header_lines(out))
        for record in _record_lines(out):
            for token in record.split("\t")[7].split(";"):
                key = token.split("=", 1)[0]
                assert re.search(
                    rf"^##INFO=<ID={re.escape(key)}[>,]", header_text,
                    flags=re.M,
                ), f"INFO key {key!r} used in a record but not declared"

    def test_every_used_format_id_is_declared(self):
        out = _full_export(QUERY_VCF)
        header_text = "\n".join(_header_lines(out))
        for record in _record_lines(out):
            for sub in record.split("\t")[8].split(":"):
                assert re.search(
                    rf"^##FORMAT=<ID={re.escape(sub)}[>,]", header_text,
                    flags=re.M,
                ), f"FORMAT sub-field {sub!r} used but not declared"

    def test_used_nonpass_filters_have_definitions(self):
        out = _full_export(QUERY_VCF)
        header_text = "\n".join(_header_lines(out))
        for record in _record_lines(out):
            filt = record.split("\t")[6]
            if filt not in (".", "PASS"):
                for name in filt.split(";"):
                    assert re.search(
                        rf"^##FILTER=<ID={re.escape(name)}[>,]", header_text,
                        flags=re.M,
                    ), f"filter {name!r} used but not defined"

    def test_record_width_matches_chrom_header(self):
        out = _full_export(QUERY_VCF)
        lines = out.splitlines()
        chrom = next(l for l in lines if l.startswith("#CHROM")).split("\t")
        for record in _record_lines(out):
            assert len(record.split("\t")) == len(chrom)


class TestReparseRoundTrip:
    def test_export_reparses_through_annotater_parser(self):
        out = _full_export(QUERY_VCF)
        d = Path(tempfile.mkdtemp())
        path = _write(d, "out.vcf", out.encode())
        df = VCFParser.parse(path)
        assert len(df) == 3
        snv = df[df["id"] == "snv1"]
        assert len(snv) == 2
        assert snv.iloc[0]["qual"] == 50.0
        assert str(snv.iloc[0]["info"]).startswith("DP=10;")
        assert snv.iloc[0]["filter"] == "PASS"
        assert snv.iloc[0]["format"] == "GT"
        assert snv.iloc[0]["S1"] == "0/1"
        dele = df[df["alt"] == "<DEL>"]
        assert len(dele) == 1
        # The END-derived span survives the round trip (1-based 300..400).
        assert int(dele.iloc[0]["start"]) == 300
        assert int(dele.iloc[0]["end"]) == 400
        assert dele.iloc[0]["filter"] == "LowQual"
        assert dele.iloc[0]["S1"] == "./."


class TestIndependentPysamValidation:
    """
    Independent of AnnotateR's own parser: pysam (already present in the
    development environment, NOT a new project dependency) must accept
    the export and see the retained metadata. Skipped where pysam is
    not installed; the structural assertions above remain the mandatory
    checks in that case.
    """

    def test_pysam_accepts_export_and_sees_retained_metadata(self):
        pysam = pytest.importorskip(
            "pysam", reason="independent VCF validation needs pysam"
        )
        out = _full_export(QUERY_VCF)
        d = Path(tempfile.mkdtemp())
        path = _write(d, "out.vcf", out.encode())

        def _scalar(value):
            # pysam returns Number=1/. INFO values as tuples.
            return value[0] if isinstance(value, tuple) else value

        with pysam.VariantFile(path) as vf:
            header = vf.header
            # Retained definitions are visible to an external consumer.
            assert "chr1" in header.contigs
            for info_id in ("DP", "END", "SVTYPE"):
                assert info_id in header.info, (
                    f"retained ##INFO declaration {info_id!r} not visible "
                    "to pysam"
                )
            assert "GT" in header.formats
            assert "LowQual" in header.filters
            # Generated provenance is visible too.
            assert any(
                line.startswith(f"##source=AnnotateR {Settings.VERSION}")
                for line in _header_lines(out)
            )
            records = list(vf)
            assert len(records) == 3
            snv = records[0]
            assert snv.chrom == "chr1" and snv.pos == 100
            assert _scalar(snv.info["DP"]) == 10
            assert snv.samples["S1"]["GT"] == (0, 1)
            dele = records[2]
            # pysam exposes INFO/END via record.stop (reserved attribute).
            assert dele.stop == 400
            assert _scalar(dele.info["SVTYPE"]) == "DEL"
            assert dele.samples["S1"]["GT"] == (None, None)