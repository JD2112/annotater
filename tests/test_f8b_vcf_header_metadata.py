class TestHeaderSurvivesExport:
    def test_original_info_dp_declaration_survives(self):
        out = _full_export(QUERY_VCF)
        assert (
            '##INFO=<ID=DP,Number=.,Type=Integer,Description="read depth">'
            in _header_lines(out)
        )

    def test_original_info_end_declaration_and_value_survive(self):
        out = _full_export(QUERY_VCF)
        header = _header_lines(out)
        assert (
            '##INFO=<ID=END,Number=1,Type=Integer,Description="end position">'
            in header
        )
        # And the corresponding record value is still there.
        assert "END=400" in _record_lines(out)[2]

    def test_original_format_gt_declaration_survives(self):
        out = _full_export(QUERY_VCF)
        assert (
            '##FORMAT=<ID=GT,Number=1,Type=String,Description="genotype">'
            in _header_lines(out)
        )

    def test_original_contig_declaration_survives(self):
        out = _full_export(QUERY_VCF)
        assert "##contig=<ID=chr1,length=1000>" in _header_lines(out)

    def test_original_filter_declaration_survives(self):
        out = _full_export(QUERY_VCF)
        assert (
            '##FILTER=<ID=LowQual,Description="low quality">'
            in _header_lines(out)
        )

    def test_annot_declarations_coexist_with_originals(self):
        out = _full_export(QUERY_VCF)
        header = _header_lines(out)
        # Originals and generated declarations side by side.
        assert '##INFO=<ID=DP,' in "\n".join(header)
        assert all(_declaration(k, c) in header for k, c in ANNOT_DECLARATIONS)
        # Every ANNOT_* key actually used in a record is declared.
        header_text = "\n".join(header)
        for record in _record_lines(out):
            info = record.split("\t")[7]
            for token in info.split(";"):
                key = token.split("=", 1)[0]
                if key.startswith("ANNOT_"):
                    assert re.search(
                        rf"^##INFO=<ID={re.escape(key)}[>,]", header_text,
                        flags=re.M,
                    ), f"emitted INFO key {key} has no ##INFO declaration"

    def test_header_metadata_emitted_once_despite_multiple_rows(self):
        # snv1 matches two genes -> three records total, but the header
        # belongs to the source VCF, not to a result row.
        out = _full_export(QUERY_VCF)
        assert len(_record_lines(out)) == 3
        assert out.count("##fileformat") == 1
        assert out.count("##contig") == 1
        assert out.count("##source=AnnotateR") == 1
        assert out.count('##INFO=<ID=DP,') == 1
        assert out.count('##FORMAT=<ID=GT,') == 1
        assert out.count('##FILTER=<ID=LowQual,') == 1

    def test_single_fileformat_preserves_source_version(self):
        out = _full_export(QUERY_VCF)
        fileformat_lines = [l for l in _header_lines(out)
                            if l.startswith("##fileformat")]
        assert fileformat_lines == ["##fileformat=VCFv4.2"]

    def test_fileformat_version_not_upgraded_or_downgraded(self):
        v41 = QUERY_VCF.replace(b"##fileformat=VCFv4.2\n",
                                b"##fileformat=VCFv4.1\n")
        out = _full_export(v41)
        fileformat_lines = [l for l in _header_lines(out)
                            if l.startswith("##fileformat")]
        assert fileformat_lines == ["##fileformat=VCFv4.1"]
        assert "##fileformat=VCFv4.2" not in out

    def test_original_metadata_order_stable_and_deterministic(self):
        out1 = _full_export(QUERY_VCF)
        out2 = _full_export(QUERY_VCF)
        header1 = _header_lines(out1)
        # Relative order of the retained originals equals source order
        # (fileformat is normalized to position 0 by contract).
        non_fileformat = [line for line in ORIGINAL_HEADER_LINES
                          if not line.startswith("##fileformat")]
        positions = [header1.index(line) for line in non_fileformat]
        assert positions == sorted(positions)
        # Generated ANNOT_* declarations come after the original block.
        last_original = max(positions)
        first_annot = min(header1.index(l) for l in header1
                          if l.startswith("##INFO=<ID=ANNOT_"))
        assert first_annot > last_original
        # Deterministic across runs.
        assert _header_lines(out1) == _header_lines(out2)

    def test_duplicate_identical_original_declaration_emitted_once(self):
        duped = QUERY_VCF.replace(
            b'##INFO=<ID=DP,Number=.,Type=Integer,Description="read depth">\n',
            b'##INFO=<ID=DP,Number=.,Type=Integer,Description="read depth">\n'
            b'##INFO=<ID=DP,Number=.,Type=Integer,Description="read depth">\n',
        )
        out = _full_export(duped)
        assert out.count(
            '##INFO=<ID=DP,Number=.,Type=Integer,Description="read depth">'
        ) == 1

    def test_multiple_fileformat_lines_collapse_to_first(self):
        qv = b"""##fileformat=VCFv4.1
##fileformat=VCFv4.2
#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO
chr1\t100\t.\tA\tT\t50\tPASS\t.
"""
        out = _full_export(qv)
        fileformats = [
            line for line in _header_lines(out)
            if line.lower().startswith("##fileformat")
        ]
        assert fileformats == ["##fileformat=VCFv4.1"]

    def test_original_source_preserved_and_annotater_source_added(self):
        with_source = QUERY_VCF.replace(
            b"##contig=<ID=chr1,length=1000>\n",
            b"##contig=<ID=chr1,length=1000>\n##source=OriginalPipeline v1.3\n",
        )
        out = _full_export(with_source)
        header = _header_lines(out)
        assert "##source=OriginalPipeline v1.3" in header
        assert f"##source=AnnotateR {Settings.VERSION}" in header
        # The original line is kept, never replaced: original order first.
        assert header.index("##source=OriginalPipeline v1.3") < \
            header.index(f"##source=AnnotateR {Settings.VERSION}")

    def test_format_and_samples_aligned_with_declarations(self):
        out = _full_export(QUERY_VCF)
        lines = out.splitlines()
        chrom = next(l for l in lines if l.startswith("#CHROM"))
        assert chrom.split("\t") == [
            "#CHROM", "POS", "ID", "REF", "ALT", "QUAL", "FILTER",
            "INFO", "FORMAT", "S1",
        ]
        for record in _record_lines(out):
            fields = record.split("\t")
            assert len(fields) == 10
            assert fields[8] in ("GT", ".")  # FORMAT aligns with the GT
            # declaration; sample value under the S1 header column.
        assert _record_lines(out)[0].split("\t")[9] == "0/1"
        assert _record_lines(out)[2].split("\t")[9] == "./."

    def test_exported_file_matches_hand_computed_expectation(self):
        out = _full_export(QUERY_VCF)
        today = pd.Timestamp.now().strftime("%Y%m%d")
        expected_header = [
            "##fileformat=VCFv4.2",
            "##contig=<ID=chr1,length=1000>",
            '##FILTER=<ID=LowQual,Description="low quality">',
            '##INFO=<ID=DP,Number=.,Type=Integer,Description="read depth">',
            '##INFO=<ID=END,Number=1,Type=Integer,Description="end position">',
            '##INFO=<ID=SVTYPE,Number=1,Type=String,'
            'Description="structural variant type">',
            '##FORMAT=<ID=GT,Number=1,Type=String,Description="genotype">',
            f"##source=AnnotateR {Settings.VERSION}",
            f"##date={today}",
        ] + [_declaration(k, c) for k, c in ANNOT_DECLARATIONS]
        expected = "\n".join(
            expected_header
            + ["#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1"]
            + EXPECTED_RECORDS
        )
        assert out == expected


