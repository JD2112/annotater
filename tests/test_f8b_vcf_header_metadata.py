"""
Task C / F8b — preservation of original VCF header (``##``) metadata.

The parse/result path retains original record values (INFO/DP, INFO/END,
FORMAT/GT, sample values, FILTER names), so the exported annotated VCF
must also carry the corresponding original ``##`` definitions —
``##contig``, ``##INFO``, ``##FORMAT``, ``##FILTER`` — otherwise the
exported file references definitions that no longer exist and is not
standards-compliant, even though AnnotateR's own parser would still
accept it.

Contract under test:
- original ``##`` lines are retained verbatim, in stable source order,
  once per source VCF (not per result row);
- exactly one ``##fileformat`` line, keeping the source's version
  (never silently upgraded/downgraded);
- original definitions are preserved, never re-synthesized;
- AnnotateR adds ``##source=AnnotateR <version>`` and ``##INFO``
  declarations for the ``ANNOT_*`` keys it emits;
- a pre-existing original declaration of an ``ANNOT_*`` ID with
  ``Type=String`` is kept as-is (no duplicate); any other type is
  refused with an explicit error (no silent overwrite);
- the export remains structurally valid and re-parses through
  AnnotateR's own VCF parser; an independent VCF library (pysam, when
  already installed) is used as an additional check where available.

Expected VCF content is hand-computed from the fixtures below — never
generated by running the exporter under test.
"""

