from streamlit_app.streamlit_app import convert_df_to_vcf

QUERY_VCF = (
    b"##fileformat=VCFv4.2\n"
    b"##contig=<ID=chr1,length=1000>\n"
    b'##FILTER=<ID=LowQual,Description="low quality">\n'
    b'##INFO=<ID=DP,Number=.,Type=Integer,Description="read depth">\n'
    b'##INFO=<ID=END,Number=1,Type=Integer,Description="end position">\n'
    b'##INFO=<ID=SVTYPE,Number=1,Type=String,Description="structural variant type">\n'
    b'##FORMAT=<ID=GT,Number=1,Type=String,Description="genotype">\n'
    b"#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
    b"chr1\t100\tsnv1\tA\tT\t50\tPASS\tDP=10\tGT\t0/1\n"
    b"chr1\t300\t.\tC\t<DEL>\t.\tLowQual\tEND=400;SVTYPE=DEL\tGT\t./.\n"
)

ORIGINAL_HEADER_LINES = [
    "##fileformat=VCFv4.2",
    "##contig=<ID=chr1,length=1000>",
    '##FILTER=<ID=LowQual,Description="low quality">',
    '##INFO=<ID=DP,Number=.,Type=Integer,Description="read depth">',
    '##INFO=<ID=END,Number=1,Type=Integer,Description="end position">',
    '##INFO=<ID=SVTYPE,Number=1,Type=String,Description="structural variant type">',
    '##FORMAT=<ID=GT,Number=1,Type=String,Description="genotype">',
]

ANNOT_GFF = (
    b"##gff-version 3\n"
    b"chr1\tens\tgene\t1\t120\t.\t+\t.\tID=geneA;Name=geneA\n"
    b"chr1\tens\tgene\t90\t110\t.\t-\t.\tID=geneB;Name=geneB\n"
    b"chr1\tens\tgene\t900\t950\t.\t+\t.\tID=geneC;Name=geneC\n"
)

ANNOT_DECLARATIONS = [
    (key, col)
    for key, col in [
        ("ANNOT_strand", "annot_strand"),
        ("ANNOT_source", "annot_source"),
        ("ANNOT_feature", "annot_feature"),
        ("ANNOT_score", "annot_score"),
        ("ANNOT_frame", "annot_frame"),
        ("ANNOT_attributes", "annot_attributes"),
        ("ANNOT_ID", "annot_ID"),
        ("ANNOT_Name", "annot_Name"),
        ("ANNOT_gene_id", "annot_gene_id"),
        ("ANNOT_gene_name", "annot_gene_name"),
        ("ANNOT_transcript_id", "annot_transcript_id"),
        ("ANNOT_gene_type", "annot_gene_type"),
        ("ANNOT_gene_biotype", "annot_gene_biotype"),
        ("ANNOT_Parent", "annot_Parent"),
    ]
]


def _declaration(key: str, col: str) -> str:
    return (
        f'##INFO=<ID={key},Number=.,Type=String,'
        f'Description="AnnotateR annotation (source column: {col})">'
    )


def _write(directory: Path, name: str, data: bytes) -> str:
    path = directory / name
    path.write_bytes(data)
    return str(path)


def _full_export(query_vcf: bytes, annot_gff: bytes = ANNOT_GFF,
                 engine_name: str = "bedtools") -> str:
    """
    Real path mirroring the app's plumbing: parse (headers retained on
    the frame) -> normalize -> engine -> canonicalize -> export with the
    retained header lines, exactly as the app passes them from session
    state to the exporter.
    """
    d = Path(tempfile.mkdtemp())
    q = parse_and_normalize(_write(d, "q.vcf", query_vcf))
    a = parse_and_normalize(_write(d, "a.gff", annot_gff))
    raw = build_engine(engine_name, mode="overlap").intersect(q, a, how="left")
    result = canonicalize_annotation_result(raw, q, a)
    return convert_df_to_vcf(result, original_header_lines=q.attrs.get(
        "vcf_header_lines"))


def _header_lines(vcf_text: str):
    return [l for l in vcf_text.splitlines() if l.startswith("##")]


def _record_lines(vcf_text: str):
    return [l for l in vcf_text.splitlines()
            if l and not l.startswith("#")]


EXPECTED_RECORDS = [
    "chr1\t100\tsnv1\tA\tT\t50\tPASS\tDP=10;ANNOT_strand=+;ANNOT_source=ens;"
    "ANNOT_feature=gene;ANNOT_attributes=ID:geneA|Name:geneA;"
    "ANNOT_ID=geneA;ANNOT_Name=geneA\tGT\t0/1",
    "chr1\t100\tsnv1\tA\tT\t50\tPASS\tDP=10;ANNOT_strand=-;ANNOT_source=ens;"
    "ANNOT_feature=gene;ANNOT_attributes=ID:geneB|Name:geneB;"
    "ANNOT_ID=geneB;ANNOT_Name=geneB\tGT\t0/1",
    "chr1\t300\t.\tC\t<DEL>\t.\tLowQual\tEND=400;SVTYPE=DEL\tGT\t./.",
]


